"""Shared dataclass models for the SecondSelf system.

Defines the core data contracts used across capture, wiki organization,
graph visualization, and question answering.
"""

from dataclasses import dataclass, field
from typing import Any

__all__ = [
    "CaptureMeta",
    "CaptureResult",
    "WikiNote",
    "GraphNode",
    "GraphEdge",
    "AskResult",
]


@dataclass
class CaptureMeta:
    """Metadata recorded for an individual raw capture item.

    Attributes:
        id: Unique identifier for the capture (e.g. '2026-07-06_a1b2c3d4').
        timestamp: ISO 8601 creation timestamp string.
        type: Type of capture ('note', 'link', or 'file').
        source: Capture source ('cli', 'stdin', or 'path').
        original_filename: Original filename if captured from a file, else None.
        content_hash: SHA-256 hash of the raw content for deduplication.
    """

    id: str
    timestamp: str
    type: str
    source: str
    original_filename: str | None
    content_hash: str


@dataclass
class CaptureResult:
    """Summary result returned after successfully capturing raw content.

    Attributes:
        id: Unique identifier assigned to the capture.
        path: Filesystem path to the created raw capture directory.
        type: Type of the captured content ('note', 'link', or 'file').
    """

    id: str
    path: str
    type: str


@dataclass
class WikiNote:
    """Structured knowledge note stored in the PARA wiki hierarchy.

    Attributes:
        id: Short unique identifier for the note (e.g. 'a1b2c3d4').
        raw_id: Identifier of the source raw capture.
        para: PARA category ('Projects', 'Areas', 'Resources', 'Archives').
        tags: Semantic topic tags assigned to the note.
        summary: Concise single-line summary generated by the LLM.
        created: ISO 8601 creation timestamp string.
        links: List of linked note IDs discovered during auto-linking.
        body: Cleaned markdown body content including wikilinks.
    """

    id: str
    raw_id: str
    para: str
    tags: list[str]
    summary: str
    created: str
    links: list[str]
    body: str


@dataclass
class GraphNode:
    """Node representation for knowledge graph export and visualization.

    Attributes:
        id: Unique identifier matching the note ID.
        label: Human-readable label (typically the note summary).
        para: PARA category of the note.
        tags: List of semantic tags.
        summary: Note summary text.
        content_preview: First ~200 characters of the note body.
        group: Grouping identifier for visual styling (matches PARA category).
    """

    id: str
    label: str
    para: str
    tags: list[str]
    summary: str
    content_preview: str
    group: str


@dataclass
class GraphEdge:
    """Directed or undirected edge between two nodes in the knowledge graph.

    Attributes:
        source: Identifier of the source node.
        target: Identifier of the target node.
        weight: Edge weight (e.g. semantic similarity score).
        type: Relationship type ('explicit' or 'semantic').
    """

    source: str
    target: str
    weight: float
    type: str


@dataclass
class AskResult:
    """Response object returned by the RAG question answering engine.

    Attributes:
        answer: Synthesized answer string from the LLM.
        sources: List of source attribution dictionaries containing note metadata.
    """

    answer: str
    sources: list[dict[str, Any]] = field(default_factory=list)

